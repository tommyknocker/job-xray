import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const distRoot = join(root, 'dist');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

const FIREFOX_ID = 'job-xray@tommyknocker';
/** `data_collection_permissions` is supported from Firefox 140 / Fenix 142. */
const FIREFOX_MIN = '140.0';
const FIREFOX_ANDROID_MIN = '142.0';

const BUNDLE_ORDER = [
    'extension/src/copy.ru.js',
    'extension/src/parser.js',
    'extension/src/metrics.js',
    'extension/src/ui.js',
    'extension/src/content.js',
];

function stripModuleSyntax(source) {
    return source
        .replace(/^import\s[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
        .replace(/^export\s+\{[^}]*\}\s*;?\s*$/gm, '')
        .replace(/^export\s+default\s+/gm, '')
        .replace(/^export\s+(?=async\s+function|function|class|const|let|var)/gm, '');
}

function sha256(buffer) {
    return createHash('sha256').update(buffer).digest('hex');
}

function baseManifest(target) {
    const manifest = {
        manifest_version: 3,
        name: 'job-xray',
        version: pkg.version,
        description: pkg.description,
        icons: {
            16: 'icons/icon16.png',
            48: 'icons/icon48.png',
            128: 'icons/icon128.png',
        },
        content_scripts: [
            {
                matches: ['*://hh.ru/*', '*://*.hh.ru/*'],
                js: ['content.js'],
                run_at: 'document_idle',
            },
        ],
    };

    if (target === 'firefox') {
        manifest.browser_specific_settings = {
            gecko: {
                id: FIREFOX_ID,
                strict_min_version: FIREFOX_MIN,
                data_collection_permissions: {
                    required: ['none'],
                },
            },
            gecko_android: {
                strict_min_version: FIREFOX_ANDROID_MIN,
            },
        };
    }

    return manifest;
}

function zipDir(outDir, zipPath) {
    execFileSync('zip', ['-X', '-r', '-q', zipPath, '.'], { cwd: outDir });
}

const bundle = [
    `/* job-xray ${pkg.version} content bundle. Generated by scripts/build.mjs. Do not edit. */`,
    ...(await Promise.all(BUNDLE_ORDER.map((rel) => readFile(join(root, rel), 'utf8')))).map(stripModuleSyntax),
].join('\n');

if (/\bimport\s/.test(bundle)) {
    throw new Error('Bundled content.js still contains import statements');
}

await rm(distRoot, { recursive: true, force: true });
await mkdir(distRoot, { recursive: true });

const artifactNames = [];
for (const target of ['chromium', 'firefox']) {
    const outDir = join(distRoot, target);
    await mkdir(join(outDir, 'icons'), { recursive: true });
    await writeFile(join(outDir, 'manifest.json'), `${JSON.stringify(baseManifest(target), null, 2)}\n`);
    await writeFile(join(outDir, 'content.js'), bundle);
    for (const icon of ['icon16.png', 'icon48.png', 'icon128.png']) {
        await copyFile(join(root, 'extension/icons', icon), join(outDir, 'icons', icon));
    }

    const zipName = `job-xray-${pkg.version}-${target}.zip`;
    const zipPath = join(distRoot, zipName);
    zipDir(outDir, zipPath);
    const zipBuf = await readFile(zipPath);
    await writeFile(join(distRoot, `job-xray-${target}.zip`), zipBuf);
    artifactNames.push(zipName, `job-xray-${target}.zip`);

    if (target === 'firefox') {
        const xpiName = `job-xray-${pkg.version}-firefox.xpi`;
        await writeFile(join(distRoot, xpiName), zipBuf);
        await writeFile(join(distRoot, 'job-xray-firefox.xpi'), zipBuf);
        artifactNames.push(xpiName, 'job-xray-firefox.xpi');
    }
}

const uniqueNames = [...new Set(artifactNames)].sort();
const sums = [];
for (const name of uniqueNames) {
    sums.push(`${sha256(await readFile(join(distRoot, name)))}  ${name}`);
}

await writeFile(join(distRoot, 'SHA256SUMS'), `${sums.join('\n')}\n`);

console.log(`built job-xray ${pkg.version}`);
for (const line of sums) {
    console.log(line);
}
